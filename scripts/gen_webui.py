#!/usr/bin/env python3
"""Builds src/helpers/wifi/WebUiPage.h from webui/companion/{index.html,proto.js}.

The page is gzipped and stored as a byte array; the node serves it with Content-Encoding: gzip.
usage: gen_webui.py          write the header
       gen_webui.py --check  exit 1 if the committed header is out of date"""
import gzip, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "webui/companion"
OUT = ROOT / "src/helpers/wifi/WebUiPage.h"

def build():
    html = (SRC / "index.html").read_text()
    proto = (SRC / "proto.js").read_text()
    assert "/*@PROTO@*/" in html, "index.html lost its codec placeholder"
    page = html.replace("/*@PROTO@*/", proto).encode()
    gz = gzip.compress(page, 9, mtime=0)      # mtime 0: same input, same bytes
    rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
    return ("// Generated by scripts/gen_webui.py from webui/companion/. Do not edit.\n"
            "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
            f"#define WEBUI_PAGE_GZ_LEN {len(gz)}   // {len(page)} bytes before compression\n"
            "static const uint8_t WEBUI_PAGE_GZ[] = {\n  " + ",\n  ".join(rows) + "\n};\n"), len(page), len(gz)

text, raw, packed = build()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("WebUiPage.h is out of date: run scripts/gen_webui.py")
    print("WebUiPage.h up to date")
else:
    OUT.write_text(text); print(f"{OUT.relative_to(ROOT)}: page {raw} bytes, gzipped {packed}")
